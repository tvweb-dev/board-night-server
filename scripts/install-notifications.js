require("dotenv").config();
const { pool } = require("../config/database");

async function install() {
  try {
    await pool.query(`CREATE TABLE IF NOT EXISTS notifications (
      NOTIFICATION_ID INT NOT NULL AUTO_INCREMENT,
      USER_ID INT NOT NULL,
      TYPE VARCHAR(40) NOT NULL,
      TITLE VARCHAR(120) NOT NULL,
      MESSAGE VARCHAR(500) NOT NULL,
      GROUP_ID INT NULL,
      EVENT_ID INT NULL,
      ACTOR_USER_ID INT NULL,
      IS_READ TINYINT(1) NOT NULL DEFAULT 0,
      CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      READ_AT DATETIME NULL,
      PRIMARY KEY (NOTIFICATION_ID),
      INDEX IDX_NOTIFICATIONS_USER_CREATED (USER_ID, CREATED_AT),
      INDEX IDX_NOTIFICATIONS_USER_UNREAD (USER_ID, IS_READ),
      CONSTRAINT FK_NOTIFICATIONS_USER FOREIGN KEY (USER_ID) REFERENCES users(USER_ID) ON DELETE CASCADE,
      CONSTRAINT FK_NOTIFICATIONS_GROUP FOREIGN KEY (GROUP_ID) REFERENCES \`groups\`(GROUP_ID) ON DELETE CASCADE,
      CONSTRAINT FK_NOTIFICATIONS_EVENT FOREIGN KEY (EVENT_ID) REFERENCES events(EVENT_ID) ON DELETE CASCADE,
      CONSTRAINT FK_NOTIFICATIONS_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES users(USER_ID) ON DELETE SET NULL
    ) ENGINE=InnoDB`);
    console.log("Notifications table installed.");
  } finally {
    await pool.end();
  }
}

install().catch((error) => { console.error(error.message); process.exitCode = 1; });
