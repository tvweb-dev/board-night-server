const CREATE_HIDDEN_FRIENDS_TABLE = `CREATE TABLE IF NOT EXISTS hidden_friends (
  USER_ID INT NOT NULL,
  FRIEND_USER_ID INT NOT NULL,
  HIDDEN_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (USER_ID, FRIEND_USER_ID),
  CONSTRAINT FK_HIDDEN_FRIENDS_USER FOREIGN KEY (USER_ID) REFERENCES users(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_HIDDEN_FRIENDS_FRIEND FOREIGN KEY (FRIEND_USER_ID) REFERENCES users(USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB`;

async function ensureFriendsSchema(database) {
  await database.query(CREATE_HIDDEN_FRIENDS_TABLE);
}

module.exports = { CREATE_HIDDEN_FRIENDS_TABLE, ensureFriendsSchema };
