const CREATE_AVAILABILITY_TABLE = `CREATE TABLE IF NOT EXISTS user_availability (
  AVAILABILITY_ID INT NOT NULL AUTO_INCREMENT,
  USER_ID INT NOT NULL,
  AVAILABILITY_DATE DATE NOT NULL,
  AVAILABILITY_STATUS ENUM('AVAILABLE', 'UNAVAILABLE', 'LIMITED') NOT NULL,
  START_TIME TIME NULL,
  END_TIME TIME NULL,
  NOTE VARCHAR(250) NULL,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (AVAILABILITY_ID),
  UNIQUE KEY UQ_USER_AVAILABILITY_DATE (USER_ID, AVAILABILITY_DATE),
  INDEX IDX_AVAILABILITY_DATE (AVAILABILITY_DATE),
  CONSTRAINT FK_AVAILABILITY_USER FOREIGN KEY (USER_ID) REFERENCES users(USER_ID) ON DELETE CASCADE
) ENGINE=InnoDB`;

async function ensureAvailabilitySchema(database) {
  await database.query(CREATE_AVAILABILITY_TABLE);
}

module.exports = { CREATE_AVAILABILITY_TABLE, ensureAvailabilitySchema };
